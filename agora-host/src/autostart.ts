import { execFile } from 'node:child_process';
import { promises as fsp, constants as fsc } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

/**
 * `agora-host autostart <enable|disable|status> --config <absolute-file>`: start the host at login
 * so hosted agents come back after a reboot. Per-user only (Task Scheduler task, systemd user
 * unit, LaunchAgent); never needs or accepts admin/root. Every external program runs through
 * execFile with an argument array, and every user path is validated before it is written into a
 * generated file.
 */

export const TASK_NAME = 'AgoraHost';
export const UNIT_NAME = 'agora-host.service';
export const AGENT_LABEL = 'com.agora.host';

export type ExecResult = { code: number; stdout: string; stderr: string };
export type Exec = (file: string, args: string[]) => Promise<ExecResult>;
export interface AutostartDeps {
    platform: NodeJS.Platform;
    exec: Exec;
    homedir: string;
    nodePath: string;
    entryPath: string;
    uid?: number;
    env: Record<string, string | undefined>;
    fs: Pick<typeof fsp, 'access' | 'mkdir' | 'readFile' | 'writeFile' | 'rm'>;
}
export class AutostartError extends Error {}

export const realExec: Exec = (file, args) => new Promise(resolve => {
    execFile(file, args, { windowsHide: true, encoding: 'utf8' }, (err, stdout, stderr) => {
        const code = err ? (typeof (err as { code?: unknown }).code === 'number' ? (err as { code: number }).code : 1) : 0;
        resolve({ code, stdout: String(stdout ?? ''), stderr: String(stderr ?? '') });
    });
});

export function defaultDeps(): AutostartDeps {
    return {
        platform: process.platform, exec: realExec, homedir: os.homedir(), nodePath: process.execPath,
        entryPath: path.join(path.dirname(fileURLToPath(import.meta.url)), 'index.js'),
        uid: typeof process.getuid === 'function' ? process.getuid() : undefined,
        env: process.env, fs: fsp,
    };
}

/** Paths go into generated files and a cmd.exe line; reject anything that could break out. */
export function assertSafePath(label: string, value: string, platform: NodeJS.Platform): void {
    if (/["\r\n\0]/.test(value)) throw new AutostartError(`${label} contains a quote or newline, which autostart will not write into a startup file.`);
    if (platform === 'win32' && /[%^&|<>!]/.test(value)) throw new AutostartError(`${label} contains one of % ^ & | < > !, which autostart will not pass through cmd.exe.`);
    if (platform !== 'win32' && value.includes('\\')) throw new AutostartError(`${label} contains a backslash, which autostart will not write into a unit file.`);
}

const xmlEscape = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;').replace(/'/g, '&apos;');
const pathOf = (p: NodeJS.Platform) => (p === 'win32' ? path.win32 : path.posix);

interface Plan { config: string; configDir: string; workDir: string; node: string; entry: string; log: string; errLog: string }

export function planFor(deps: AutostartDeps, config: string): Plan {
    const P = pathOf(deps.platform);
    const configDir = P.dirname(config);
    const entry = deps.entryPath;
    const plan: Plan = {
        config, configDir, node: deps.nodePath, entry, workDir: P.dirname(P.dirname(entry)),
        log: P.join(configDir, 'host.log'), errLog: P.join(configDir, 'host.err.log'),
    };
    for (const [k, v] of Object.entries({ 'The config path': config, 'The node path': plan.node, 'The host entry path': entry, 'The host folder': plan.workDir }))
        assertSafePath(k, v, deps.platform);
    return plan;
}

export const commandLine = (p: Plan) => `${p.node} ${p.entry} --config ${p.config}`;

// ---------- Windows ----------

export function windowsLauncher(p: Plan): string {
    const q = (s: string) => s.replace(/"/g, '""'); // VBScript string literal escaping
    const cmd = `cmd.exe /c ""${p.node}" "${p.entry}" --config "${p.config}" >> "${p.log}" 2>> "${p.errLog}""`;
    return [
        "' Generated by `agora-host autostart enable`. Runs the host hidden; logs go to host.log and host.err.log.",
        'Set sh = CreateObject("WScript.Shell")',
        `sh.CurrentDirectory = "${q(p.workDir)}"`,
        `WScript.Quit sh.Run("${q(cmd)}", 0, True)`,
        '',
    ].join('\r\n');
}

export function windowsTaskXml(p: Plan, user: string, launcher: string): string {
    return `<?xml version="1.0" encoding="UTF-16"?>
<Task version="1.4" xmlns="http://schemas.microsoft.com/windows/2004/02/mit/task">
  <RegistrationInfo><Description>Starts the Agora host at logon so hosted agents come back after a reboot.</Description></RegistrationInfo>
  <Triggers>
    <LogonTrigger><Enabled>true</Enabled><UserId>${xmlEscape(user)}</UserId></LogonTrigger>
  </Triggers>
  <Principals>
    <Principal id="Author"><UserId>${xmlEscape(user)}</UserId><LogonType>InteractiveToken</LogonType><RunLevel>LeastPrivilege</RunLevel></Principal>
  </Principals>
  <Settings>
    <MultipleInstancesPolicy>IgnoreNew</MultipleInstancesPolicy>
    <DisallowStartIfOnBatteries>false</DisallowStartIfOnBatteries>
    <StopIfGoingOnBatteries>false</StopIfGoingOnBatteries>
    <StartWhenAvailable>true</StartWhenAvailable>
    <ExecutionTimeLimit>PT0S</ExecutionTimeLimit>
    <Hidden>true</Hidden>
    <RestartOnFailure><Interval>PT1M</Interval><Count>999</Count></RestartOnFailure>
  </Settings>
  <Actions Context="Author">
    <Exec>
      <Command>wscript.exe</Command>
      <Arguments>//B //Nologo "${xmlEscape(launcher)}"</Arguments>
      <WorkingDirectory>${xmlEscape(p.workDir)}</WorkingDirectory>
    </Exec>
  </Actions>
</Task>
`;
}

function windowsUser(deps: AutostartDeps): string {
    const name = deps.env.USERNAME ?? '';
    const dom = deps.env.USERDOMAIN ?? '';
    const user = dom ? `${dom}\\${name}` : name;
    if (!name || /["\r\n\0<>|/*?:]/.test(user.replace('\\', ''))) throw new AutostartError('Could not determine a safe Windows user name for the task.');
    return user;
}

async function windowsElevated(deps: AutostartDeps): Promise<boolean> {
    const r = await deps.exec('whoami', ['/groups']);
    return r.stdout.includes('S-1-16-12288'); // High mandatory level = elevated token
}

export function parseSchtasksList(stdout: string): { status: string; run: string } {
    const field = (key: string) => stdout.split(/\r?\n/).map(l => l.match(new RegExp(`^\\s*${key}:\\s*(.*)$`, 'i'))).find(Boolean)?.[1]?.trim() ?? '';
    return { status: field('Status'), run: field('Task To Run') };
}

// ---------- Linux ----------

const sdQuote = (s: string) => `"${s.replace(/%/g, '%%').replace(/\$/g, '$$$$')}"`;

export function systemdUnit(p: Plan, pathEnv?: string): string {
    const sdPlain = (s: string) => s.replace(/%/g, '%%');
    const lines = [
        '# Generated by `agora-host autostart enable`. Remove with `agora-host autostart disable`.',
        '[Unit]', 'Description=Agora host (leased agent sessions)', 'After=network-online.target', 'Wants=network-online.target', '',
        '[Service]',
        `ExecStart=${sdQuote(p.node)} ${sdQuote(p.entry)} --config ${sdQuote(p.config)}`,
        `WorkingDirectory=${sdPlain(p.workDir)}`,
        `StandardOutput=append:${sdPlain(p.log)}`, `StandardError=append:${sdPlain(p.errLog)}`,
    ];
    if (pathEnv && !/["\r\n\\]/.test(pathEnv)) lines.push(`Environment=${sdQuote(`PATH=${pathEnv}`)}`);
    lines.push('Restart=on-failure', 'RestartSec=10', '', '[Install]', 'WantedBy=default.target', '');
    return lines.join('\n');
}

// ---------- macOS ----------

export function launchAgentPlist(p: Plan, pathEnv?: string): string {
    const s = (v: string) => `    <string>${xmlEscape(v)}</string>`;
    const env = pathEnv && !/[\r\n]/.test(pathEnv)
        ? `  <key>EnvironmentVariables</key>\n  <dict><key>PATH</key><string>${xmlEscape(pathEnv)}</string></dict>\n` : '';
    return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key><string>${AGENT_LABEL}</string>
  <key>ProgramArguments</key>
  <array>
${s(p.node)}
${s(p.entry)}
${s('--config')}
${s(p.config)}
  </array>
  <key>WorkingDirectory</key><string>${xmlEscape(p.workDir)}</string>
  <key>StandardOutPath</key><string>${xmlEscape(p.log)}</string>
  <key>StandardErrorPath</key><string>${xmlEscape(p.errLog)}</string>
${env}  <key>RunAtLoad</key><true/>
  <key>KeepAlive</key><true/>
  <key>ThrottleInterval</key><integer>30</integer>
</dict>
</plist>
`;
}

// ---------- commands ----------

export interface Status { installed: boolean; enabled: boolean; running: boolean; command: string | null }

const unitPath = (d: AutostartDeps) => path.posix.join(d.homedir, '.config', 'systemd', 'user', UNIT_NAME);
const plistPath = (d: AutostartDeps) => path.posix.join(d.homedir, 'Library', 'LaunchAgents', `${AGENT_LABEL}.plist`);
const launcherPath = (p: Plan) => path.win32.join(p.configDir, 'agora-host-autostart.vbs');
const guiDomain = (d: AutostartDeps) => `gui/${d.uid}`;

async function mustRun(deps: AutostartDeps, file: string, args: string[], what: string): Promise<ExecResult> {
    const r = await deps.exec(file, args);
    if (r.code !== 0) throw new AutostartError(`${what} failed (${file} exit ${r.code})${r.stderr.trim() ? `: ${r.stderr.trim().split('\n')[0]}` : ''}`);
    return r;
}

async function readIfExists(deps: AutostartDeps, file: string): Promise<string | null> {
    try { return await deps.fs.readFile(file, 'utf8'); } catch { return null; }
}

export async function statusOf(deps: AutostartDeps): Promise<Status> {
    if (deps.platform === 'win32') {
        const r = await deps.exec('schtasks', ['/Query', '/TN', TASK_NAME, '/V', '/FO', 'LIST']);
        if (r.code !== 0) return { installed: false, enabled: false, running: false, command: null };
        const { status, run } = parseSchtasksList(r.stdout);
        return { installed: true, enabled: !/disabled/i.test(status), running: /running/i.test(status), command: run || null };
    }
    if (deps.platform === 'linux') {
        const r = await deps.exec('systemctl', ['--user', 'show', UNIT_NAME, '-p', 'LoadState', '-p', 'ActiveState', '-p', 'UnitFileState']);
        const kv = Object.fromEntries(r.stdout.split('\n').map(l => l.split(/=(.*)/s).slice(0, 2)).filter(a => a.length === 2));
        const unit = await readIfExists(deps, unitPath(deps));
        const installed = r.code === 0 && kv.LoadState === 'loaded' && unit !== null;
        return {
            installed, enabled: installed && kv.UnitFileState === 'enabled', running: installed && kv.ActiveState === 'active',
            command: unit?.match(/^ExecStart=(.*)$/m)?.[1] ?? null,
        };
    }
    if (deps.platform === 'darwin') {
        const plist = await readIfExists(deps, plistPath(deps));
        const r = await deps.exec('launchctl', ['print', `${guiDomain(deps)}/${AGENT_LABEL}`]);
        const loaded = r.code === 0;
        const args = plist ? [...plist.matchAll(/<string>([^<]*)<\/string>/g)].map(m => m[1]).slice(1, 5) : [];
        return {
            installed: plist !== null, enabled: plist !== null && loaded, running: loaded && /^\s*state = running\s*$/m.test(r.stdout),
            command: args.length === 4 ? args.join(' ') : null,
        };
    }
    throw new AutostartError(`Autostart is not supported on ${deps.platform}.`);
}

async function checkConfig(deps: AutostartDeps, config: string | undefined): Promise<string> {
    if (!config) throw new AutostartError('--config <absolute-file> is required.');
    if (!pathOf(deps.platform).isAbsolute(config)) throw new AutostartError('--config must be an absolute path (a relative path would break when the host starts from another folder).');
    try { await deps.fs.access(config, fsc.R_OK); } catch { throw new AutostartError('The config file does not exist or is not readable.'); }
    return config;
}

function refuseRoot(deps: AutostartDeps): void {
    if (deps.platform !== 'win32' && deps.uid === 0) throw new AutostartError('Do not run autostart as root; it installs a per-user service for your normal account.');
}

export async function enable(deps: AutostartDeps, configArg: string | undefined, out: (l: string) => void): Promise<void> {
    refuseRoot(deps);
    const config = await checkConfig(deps, configArg);
    const p = planFor(deps, config);
    if (deps.platform === 'win32') {
        if (await windowsElevated(deps)) throw new AutostartError('This shell is running as administrator. Open a normal (non-admin) terminal; the task is per-user.');
        const launcher = launcherPath(p);
        assertSafePath('The launcher path', launcher, 'win32');
        const user = windowsUser(deps);
        const xmlFile = path.win32.join(p.configDir, 'agora-host-task.xml');
        await deps.fs.writeFile(launcher, windowsLauncher(p), 'utf8');
        // schtasks reads UTF-16 with a BOM
        await deps.fs.writeFile(xmlFile, Buffer.concat([Buffer.from([0xff, 0xfe]), Buffer.from(windowsTaskXml(p, user, launcher), 'utf16le')]));
        try { await mustRun(deps, 'schtasks', ['/Create', '/TN', TASK_NAME, '/XML', xmlFile, '/F'], 'Creating the scheduled task'); }
        finally { await deps.fs.rm(xmlFile, { force: true }); }
        if (!(await statusOf(deps)).running) await mustRun(deps, 'schtasks', ['/Run', '/TN', TASK_NAME], 'Starting the scheduled task');
    } else if (deps.platform === 'linux') {
        const file = unitPath(deps);
        const body = systemdUnit(p, deps.env.PATH);
        const changed = (await readIfExists(deps, file)) !== body;
        await deps.fs.mkdir(path.posix.dirname(file), { recursive: true });
        await deps.fs.writeFile(file, body, 'utf8');
        await mustRun(deps, 'systemctl', ['--user', 'daemon-reload'], 'Reloading systemd');
        await mustRun(deps, 'systemctl', ['--user', 'enable', '--now', UNIT_NAME], 'Enabling the unit');
        if (changed) await mustRun(deps, 'systemctl', ['--user', 'restart', UNIT_NAME], 'Restarting the unit');
    } else if (deps.platform === 'darwin') {
        if (deps.uid === undefined) throw new AutostartError('Could not determine your user id.');
        const file = plistPath(deps);
        await deps.fs.mkdir(path.posix.dirname(file), { recursive: true });
        await deps.fs.writeFile(file, launchAgentPlist(p, deps.env.PATH), 'utf8');
        await deps.exec('launchctl', ['bootout', `${guiDomain(deps)}/${AGENT_LABEL}`]); // not loaded yet is fine
        await mustRun(deps, 'launchctl', ['bootstrap', guiDomain(deps), file], 'Loading the LaunchAgent');
    } else throw new AutostartError(`Autostart is not supported on ${deps.platform}.`);
    out(`Autostart enabled. Command: ${commandLine(p)}`);
    out(`Logs: ${p.log} and ${p.errLog}`);
}

export async function disable(deps: AutostartDeps, out: (l: string) => void): Promise<void> {
    refuseRoot(deps);
    if (deps.platform === 'win32') {
        if (await windowsElevated(deps)) throw new AutostartError('This shell is running as administrator. Open a normal (non-admin) terminal; the task is per-user.');
        const before = await statusOf(deps);
        if (before.installed) {
            await deps.exec('schtasks', ['/End', '/TN', TASK_NAME]);
            await mustRun(deps, 'schtasks', ['/Delete', '/TN', TASK_NAME, '/F'], 'Deleting the scheduled task');
        }
        // The launcher sits next to the config; its location is in the task's command line.
        const m = before.command?.match(/"([^"]*agora-host-autostart\.vbs)"/);
        if (m) await deps.fs.rm(m[1], { force: true });
    } else if (deps.platform === 'linux') {
        await deps.exec('systemctl', ['--user', 'disable', '--now', UNIT_NAME]);
        await deps.fs.rm(unitPath(deps), { force: true });
        await deps.exec('systemctl', ['--user', 'daemon-reload']);
    } else if (deps.platform === 'darwin') {
        if (deps.uid === undefined) throw new AutostartError('Could not determine your user id.');
        await deps.exec('launchctl', ['bootout', `${guiDomain(deps)}/${AGENT_LABEL}`]);
        await deps.fs.rm(plistPath(deps), { force: true });
    } else throw new AutostartError(`Autostart is not supported on ${deps.platform}.`);
    out('Autostart disabled and removed. A host that is already running keeps running until you stop it.');
}

export async function autostartCommand(argv: string[], out: (l: string) => void = console.log, deps: AutostartDeps = defaultDeps()): Promise<number> {
    const action = argv[0];
    const i = argv.indexOf('--config');
    const config = i > 0 ? argv[i + 1] : undefined;
    if (!['enable', 'disable', 'status'].includes(action ?? '')) {
        out('Usage: agora-host autostart <enable|disable|status> --config <absolute-file>');
        return 2;
    }
    try {
        if (action === 'enable') await enable(deps, config, out);
        else if (action === 'disable') await disable(deps, out);
        else {
            const s = await statusOf(deps);
            out(`installed: ${s.installed ? 'yes' : 'no'}`);
            out(`enabled: ${s.enabled ? 'yes' : 'no'}`);
            out(`running: ${s.running ? 'yes' : 'no'}`);
            out(`command: ${s.command ?? '(none)'}`);
        }
        return 0;
    } catch (err) {
        out(err instanceof AutostartError ? err.message : 'Autostart failed unexpectedly.');
        return 1;
    }
}
