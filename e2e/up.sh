#!/usr/bin/env bash
# Bring up the disposable agora-e2e instance on this machine's Docker daemon.
# Safe next to the live `agora` stack: own project, network, volumes, ports, image tags,
# and no runner/socket-proxy/cap-gateway/caddy. See e2e/README.md.
set -euo pipefail

PROJECT=agora-e2e
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
COMPOSE_FILE="$HERE/docker-compose.e2e.yml"
ENV_FILE="$HERE/.env.e2e"
SERVICES=(postgres redis migrate api web)
FORBIDDEN=(runner socket-proxy sandbox-image cap-gateway caddy tailscale)
API_PORT="${E2E_API_PORT:-3200}"
WEB_PORT="${E2E_WEB_PORT:-8280}"

die() { echo "up.sh: $*" >&2; exit 1; }
compose() { docker compose -p "$PROJECT" -f "$COMPOSE_FILE" --env-file "$ENV_FILE" "$@"; }

# ---- env (fresh random secrets, written only here, gitignored) ----
if [ ! -f "$ENV_FILE" ] || [ "${E2E_FRESH_ENV:-0}" = 1 ]; then
  umask 077
  rnd() { head -c "$1" /dev/urandom | od -An -tx1 | tr -d ' \n'; }
  cat > "$ENV_FILE" <<ENVEOF
# Generated by e2e/up.sh on $(date -u +%FT%TZ). Disposable test instance only. Gitignored.
DB_PASSWORD=$(rnd 24)
JWT_SECRET=$(rnd 48)
AGORA_ENCRYPTION_KEY=$(rnd 32)
AGORA_SETUP_TOKEN=$(rnd 24)
# Seeded test-user passwords (fake accounts on this instance only). The CANARY marker lets
# the leak scanner find them in any retained evidence.
E2E_OWNER_PASSWORD=CANARY-owner-$(rnd 12)-SECRET
E2E_MEMBER_PASSWORD=CANARY-member-$(rnd 12)-SECRET
E2E_API_PORT=$API_PORT
E2E_WEB_PORT=$WEB_PORT
E2E_BASE_URL=http://localhost:$WEB_PORT
ENVEOF
  echo "up.sh: wrote fresh $ENV_FILE"
fi

# ---- preflight ----
echo "== preflight =="
free -m | awk 'NR==1||/Mem:/'
df -h / | awk 'NR==1||NR==2'
avail_mb=$(free -m | awk '/Mem:/{print $7}')
avail_disk_gb=$(df -BG --output=avail / | tail -1 | tr -dc 0-9)
[ "$avail_mb" -ge 2048 ] || die "less than 2 GB RAM available ($avail_mb MB)"
[ "$avail_disk_gb" -ge 10 ] || die "less than 10 GB disk available (${avail_disk_gb} GB)"

svc_list=$(compose config --services)
for f in "${FORBIDDEN[@]}"; do
  if echo "$svc_list" | grep -qx "$f"; then die "compose file defines forbidden service '$f'"; fi
done
rendered=$(compose config --format json)
echo "$rendered" | grep -q '"name": *"agora-e2e"' || die "rendered project name is not agora-e2e"
if echo "$rendered" | grep -q '"agora_default"\|"agora_sandbox"\|"agora_pgdata"\|"agora_files-data"'; then
  die "rendered config references a live agora network/volume"
fi
for p in "$API_PORT" "$WEB_PORT"; do
  case "$p" in 80|443|3000|8080) die "port $p belongs to the live stack";; esac
  if docker ps --format '{{.Names}} {{.Ports}}' | grep -v "^${PROJECT}-" | grep -q ":$p->"; then
    die "port $p is already published by another container"
  fi
done
echo "services: ${SERVICES[*]} (runner/socket-proxy/cap-gateway/caddy excluded)"
echo "ports: api 127.0.0.1:$API_PORT  web 127.0.0.1:$WEB_PORT"
echo "live stack containers (not touched):"
docker ps --filter label=com.docker.compose.project=agora --format '  {{.Names}}' || true

# ---- start ----
compose up -d --build "${SERVICES[@]}"

echo "== waiting for health =="
for i in $(seq 1 90); do
  if curl -fsS "http://127.0.0.1:$API_PORT/health" >/dev/null 2>&1 \
     && curl -fsS "http://127.0.0.1:$WEB_PORT/health" >/dev/null 2>&1; then
    echo "agora-e2e is up: web http://localhost:$WEB_PORT  api http://localhost:$API_PORT"
    exit 0
  fi
  sleep 2
done
compose ps
compose logs --tail 50 api
die "instance did not become healthy"
