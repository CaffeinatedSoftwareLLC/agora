# Shared helpers for the e2e/ops scripts. Source it; do not run it.
#
# Only two compose projects are allowed: agora-ops (api 3300, web 8380) and
# agora-ops-restore (api 3400, web 8480). Before every up AND every down, the rendered
# compose config is parsed and every service, volume, network and published port is
# checked (validate_compose.py), and published ports are checked against running
# containers. Every file these scripts write lives in the gitignored e2e/ops/.state/.
# Nothing here touches the agora or agora-e2e projects.

OPS_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
OPS_REPO="$(cd "$OPS_DIR/../.." && pwd)"
OPS_COMPOSE_FILE="$OPS_DIR/docker-compose.ops.yml"
# Compose files in use; only guard-selftest.sh adds one (a throwaway override in .state)
OPS_COMPOSE_ARGS=(-f "$OPS_COMPOSE_FILE")
OPS_STATE="$OPS_DIR/.state"

die() { echo "ops: $*" >&2; exit 1; }
log() { echo "== $* =="; }

[ -L "$OPS_STATE" ] && die "$OPS_STATE is a symlink"
mkdir -p "$OPS_STATE"; chmod 700 "$OPS_STATE"
OPS_STATE_REAL="$(realpath "$OPS_STATE")"

# state_path <path>: print the canonical path, or die unless it resolves inside .state/
# (symlinks are resolved first, so a link pointing out of .state is refused).
state_path() {
  local p; p="$(realpath -m -- "$1")" || die "cannot resolve '$1'"
  case "$p" in "$OPS_STATE_REAL"/?*) printf '%s\n' "$p" ;; *) die "refusing path outside $OPS_STATE: $1" ;; esac
}

# ops_use <project>: select a project, its ports and its env file.
ops_use() {
  OPS_PROJECT="$1"
  case "$OPS_PROJECT" in
    agora-ops)         OPS_API_PORT=3300; OPS_WEB_PORT=8380 ;;
    agora-ops-restore) OPS_API_PORT=3400; OPS_WEB_PORT=8480 ;;
    *) die "refusing project '$OPS_PROJECT' (only agora-ops, agora-ops-restore)" ;;
  esac
  OPS_ENV_FILE="$(state_path "$OPS_STATE/$OPS_PROJECT.env")" || exit 1
  OPS_BASE="http://127.0.0.1:$OPS_API_PORT"
  export OPS_PROJECT OPS_API_PORT OPS_WEB_PORT
  export OPS_SERVER_IMAGE="${OPS_SERVER_IMAGE:-agora-ops-server:new}"
  export OPS_BUILD_CONTEXT="${OPS_BUILD_CONTEXT:-$OPS_REPO}"
}

ocompose() { docker compose -p "$OPS_PROJECT" "${OPS_COMPOSE_ARGS[@]}" --env-file "$OPS_ENV_FILE" "$@"; }

rnd() { head -c "$1" /dev/urandom | od -An -tx1 | tr -d ' \n'; }

# ops_gen_env <file in .state>: fresh random secrets for a disposable instance.
ops_gen_env() {
  local f; f="$(state_path "$1")" || exit 1
  ( umask 077
    cat > "$f" <<ENVEOF
# Generated by e2e/ops on $(date -u +%FT%TZ). Disposable test instance only. Gitignored.
DB_PASSWORD=$(rnd 24)
JWT_SECRET=$(rnd 48)
AGORA_ENCRYPTION_KEY=$(rnd 32)
AGORA_SETUP_TOKEN=$(rnd 24)
OPS_OWNER_PASSWORD=CANARY-owner-$(rnd 12)-SECRET
OPS_MEMBER_PASSWORD=CANARY-member-$(rnd 12)-SECRET
ENVEOF
  )
}

# ops_copy <src> <dest in .state>: copy a secrets file, mode 600.
ops_copy() {
  local d; d="$(state_path "$2")" || exit 1
  ( umask 077; cat "$1" > "$d" ); chmod 600 "$d"
}

env_get() { grep -E "^$2=" "$1" | tail -1 | cut -d= -f2-; }
env_set() {  # env_set <file in .state> <key> <value>; the temp copy stays in .state
  local f tmp; f="$(state_path "$1")" || exit 1
  tmp="$(umask 077; mktemp "$OPS_STATE_REAL/.tmp.XXXXXX")"
  grep -vE "^$2=" "$f" > "$tmp" || true
  echo "$2=$3" >> "$tmp"
  cat "$tmp" > "$f"; rm -f "$tmp"
}

# ops_validate: parse the rendered config (all profiles) and check every service,
# volume, network and published port; then that no other container publishes those
# ports. Used before every up and every down.
ops_validate() {
  local rendered ports p
  rendered=$(ocompose --profile web config --format json) || die "compose config failed"
  ports=$(printf '%s' "$rendered" | python3 -I "$OPS_DIR/validate_compose.py" "$OPS_PROJECT" "$OPS_API_PORT" "$OPS_WEB_PORT") \
    || { printf '%s\n' "$ports" >&2; die "compose guard refused $OPS_PROJECT"; }
  for p in $ports; do
    if docker ps --format '{{.Label "com.docker.compose.project"}} {{.Ports}}' | grep -v "^${OPS_PROJECT} " | grep -q ":$p->"; then
      die "port $p is already published by a container outside $OPS_PROJECT"
    fi
  done
}

# ops_up [services...]: guarded start (no build unless OPS_BUILD=1).
ops_up() {
  [ -f "$OPS_ENV_FILE" ] || die "no env file $OPS_ENV_FILE"
  ops_validate
  local build=--no-build services=("$@")
  [ "${OPS_BUILD:-0}" = 1 ] && build=--build
  [ ${#services[@]} -gt 0 ] || services=(postgres redis migrate api)
  log "$OPS_PROJECT up ($OPS_SERVER_IMAGE: ${services[*]})"
  ocompose up -d $build "${services[@]}"
}

# ops_wait_api [seconds]: 0 when /health answers, 1 on timeout.
ops_wait_api() {
  local n=$(( ${1:-180} / 2 )) i
  for i in $(seq 1 "$n"); do
    curl -fsS "$OPS_BASE/health" >/dev/null 2>&1 && return 0
    sleep 2
  done
  return 1
}

# ops_down: remove only the selected project (containers, volumes, network), after the
# same validation as ops_up. Without an env file, compose parses the file with dummy
# values from a throwaway env file in .state.
ops_down() {
  case "$OPS_PROJECT" in agora-ops|agora-ops-restore) ;; *) die "refusing to remove '$OPS_PROJECT'";; esac
  local saved="$OPS_ENV_FILE" dummy=""
  if [ ! -f "$OPS_ENV_FILE" ]; then
    dummy="$(umask 077; mktemp "$OPS_STATE_REAL/.down.XXXXXX")"
    printf 'DB_PASSWORD=x\nJWT_SECRET=x\nAGORA_ENCRYPTION_KEY=x\nAGORA_SETUP_TOKEN=x\n' > "$dummy"
    OPS_ENV_FILE="$dummy"
  fi
  local rc=0
  ( ops_validate && ocompose --profile web down -v --remove-orphans ) || rc=$?
  OPS_ENV_FILE="$saved"
  [ -n "$dummy" ] && rm -f "$dummy"
  return $rc
}

ops_psql() { ocompose exec -T postgres psql -U accord -d agora -v ON_ERROR_STOP=1 -At "$@"; }

ops_api() { python3 -I "$OPS_DIR/opsapi.py" --state "$OPS_STATE_REAL" "$@"; }
