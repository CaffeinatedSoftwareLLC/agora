# Shared helpers for the e2e/ops scripts. Source it; do not run it.
#
# Only two compose projects are allowed: agora-ops (api 3300, web 8380) and
# agora-ops-restore (api 3400, web 8480). The guards are the ones in e2e/up.sh: no
# runner/socket-proxy/cap-gateway/caddy, no live `agora_*` volume or network, no live
# or already-published port. Nothing here touches the agora or agora-e2e projects.

OPS_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
OPS_REPO="$(cd "$OPS_DIR/../.." && pwd)"
OPS_COMPOSE_FILE="$OPS_DIR/docker-compose.ops.yml"
OPS_STATE="${OPS_STATE:-$OPS_DIR/.state}"
OPS_FORBIDDEN=(runner socket-proxy sandbox-image cap-gateway caddy tailscale)

die() { echo "ops: $*" >&2; exit 1; }
log() { echo "== $* =="; }

# ops_use <project>: select a project, its ports and its env file.
ops_use() {
  OPS_PROJECT="$1"
  case "$OPS_PROJECT" in
    agora-ops)         OPS_API_PORT=3300; OPS_WEB_PORT=8380 ;;
    agora-ops-restore) OPS_API_PORT=3400; OPS_WEB_PORT=8480 ;;
    *) die "refusing project '$OPS_PROJECT' (only agora-ops, agora-ops-restore)" ;;
  esac
  OPS_ENV_FILE="${OPS_ENV_FILE_OVERRIDE:-$OPS_STATE/$OPS_PROJECT.env}"
  OPS_BASE="http://127.0.0.1:$OPS_API_PORT"
  export OPS_PROJECT OPS_API_PORT OPS_WEB_PORT
  export OPS_SERVER_IMAGE="${OPS_SERVER_IMAGE:-agora-ops-server:new}"
  export OPS_BUILD_CONTEXT="${OPS_BUILD_CONTEXT:-$OPS_REPO}"
}

ocompose() { docker compose -p "$OPS_PROJECT" -f "$OPS_COMPOSE_FILE" --env-file "$OPS_ENV_FILE" "$@"; }

rnd() { head -c "$1" /dev/urandom | od -An -tx1 | tr -d ' \n'; }

# ops_gen_env <file>: fresh random secrets for a disposable instance.
ops_gen_env() {
  mkdir -p "$(dirname "$1")"
  ( umask 077
    cat > "$1" <<ENVEOF
# Generated by e2e/ops on $(date -u +%FT%TZ). Disposable test instance only. Gitignored.
DB_PASSWORD=$(rnd 24)
JWT_SECRET=$(rnd 48)
AGORA_ENCRYPTION_KEY=$(rnd 32)
AGORA_SETUP_TOKEN=$(rnd 24)
OPS_OWNER_PASSWORD=CANARY-owner-$(rnd 12)-SECRET
OPS_MEMBER_PASSWORD=CANARY-member-$(rnd 12)-SECRET
ENVEOF
  )
}

env_get() { grep -E "^$2=" "$1" | tail -1 | cut -d= -f2-; }
env_set() {  # env_set <file> <key> <value>
  local tmp; tmp="$(mktemp)"
  grep -vE "^$2=" "$1" > "$tmp" || true
  echo "$2=$3" >> "$tmp"
  cat "$tmp" > "$1"; rm -f "$tmp"
}

# ops_guard: refuse to start anything that could touch the live or e2e stacks.
ops_guard() {
  [ -f "$OPS_ENV_FILE" ] || die "no env file $OPS_ENV_FILE"
  local svc_list rendered f p
  svc_list=$(ocompose --profile web config --services)
  for f in "${OPS_FORBIDDEN[@]}"; do
    if echo "$svc_list" | grep -qx "$f"; then die "compose file defines forbidden service '$f'"; fi
  done
  rendered=$(ocompose --profile web config --format json)
  echo "$rendered" | grep -q "\"name\": *\"$OPS_PROJECT\"" || die "rendered project name is not $OPS_PROJECT"
  if echo "$rendered" | grep -q '"agora_[a-z-]*"\|"agora-e2e'; then
    die "rendered config references a live agora_* or agora-e2e network/volume"
  fi
  echo "$rendered" | grep -q "\"$OPS_PROJECT""_net\"" || die "rendered network is not ${OPS_PROJECT}_net"
  for p in "$OPS_API_PORT" "$OPS_WEB_PORT"; do
    case "$p" in 80|443|3000|8080|3200|8280) die "port $p belongs to the live or e2e stack";; esac
    if docker ps --format '{{.Names}} {{.Ports}}' | grep -v "^${OPS_PROJECT}-" | grep -q ":$p->"; then
      die "port $p is already published by another container"
    fi
  done
}

# ops_up [services...]: guarded start (no build unless OPS_BUILD=1).
ops_up() {
  ops_guard
  local build=--no-build services=("$@")
  [ "${OPS_BUILD:-0}" = 1 ] && build=--build
  [ ${#services[@]} -gt 0 ] || services=(postgres redis migrate api)
  log "$OPS_PROJECT up ($OPS_SERVER_IMAGE: ${services[*]})"
  ocompose up -d $build "${services[@]}"
}

# ops_wait_api [seconds]: 0 when /health answers, 1 on timeout.
ops_wait_api() {
  local n=$(( ${1:-180} / 2 )) i
  for i in $(seq 1 "$n"); do
    curl -fsS "$OPS_BASE/health" >/dev/null 2>&1 && return 0
    sleep 2
  done
  return 1
}

# ops_down: remove only the selected project (containers, volumes, network).
ops_down() {
  case "$OPS_PROJECT" in agora-ops|agora-ops-restore) ;; *) die "refusing to remove '$OPS_PROJECT'";; esac
  if [ -f "$OPS_ENV_FILE" ]; then
    ocompose --profile web down -v --remove-orphans
  else
    DB_PASSWORD=x JWT_SECRET=x AGORA_ENCRYPTION_KEY=x AGORA_SETUP_TOKEN=x \
      docker compose -p "$OPS_PROJECT" -f "$OPS_COMPOSE_FILE" --profile web down -v --remove-orphans
  fi
}

ops_psql() { ocompose exec -T postgres psql -U accord -d agora -v ON_ERROR_STOP=1 -At "$@"; }

ops_api() { python3 -I "$OPS_DIR/opsapi.py" "$@"; }
